-- 4. Посты. Без них расчёт свободных окон возвращает пустоту: в
-- calculateAvailableSlots пустой список постов или мастеров означает
-- «записаться нельзя», поэтому каждому автосервису нужно минимум два поста.
INSERT INTO service_bays (id, service_center_id, name, bay_type, is_active)
SELECT
    ('d0110000-0000-0000-0000-0000000000' || LPAD((ROW_NUMBER() OVER (ORDER BY c.id, t.pos))::TEXT, 2, '0'))::uuid,
    c.id,
    t.bay_name,
    t.bay_type,
    TRUE
FROM service_centers c
CROSS JOIN (VALUES
    (1, 'Пост №1 (подъёмник)', 'lift'),
    (2, 'Пост №2 (диагностика)', 'diagnostics')
) AS t(pos, bay_name, bay_type)
WHERE c.id::TEXT LIKE 'c0110000-%'
ON CONFLICT (id) DO NOTHING;

-- 5. Мастера. Работают все дни недели, иначе в выдаче не будет окон в выходные
