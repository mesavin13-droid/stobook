) AS t(pos, master_name, specialization)
WHERE c.id::TEXT LIKE 'c0110000-%'
ON CONFLICT (id) DO NOTHING;

-- 6. Часы работы. Режим «Автомаркета Е» взят с его сайта: Пн-Пт 09:00–19:00,
-- Сб-Вс 10:00–18:00. Остальные станции работают ежедневно 09:00–20:00.
INSERT INTO business_hours (service_center_id, day_of_week, open_time, close_time, is_closed)
SELECT c.id, d,
    CASE
        WHEN c.id::TEXT = 'c0110000-0000-0000-0000-000000000011' AND d IN (0, 6) THEN '10:00'::TIME
        ELSE '09:00'::TIME
    END,
    CASE
        WHEN c.id::TEXT = 'c0110000-0000-0000-0000-000000000011' AND d IN (0, 6) THEN '18:00'::TIME
        WHEN c.id::TEXT = 'c0110000-0000-0000-0000-000000000011' THEN '19:00'::TIME
        ELSE '20:00'::TIME
    END,
    FALSE
FROM service_centers c
CROSS JOIN generate_series(0, 6) AS d
WHERE c.id::TEXT LIKE 'c0110000-%'
ON CONFLICT (service_center_id, day_of_week) DO NOTHING;

