INSERT INTO masters (id, service_center_id, full_name, phone, specialization, is_active, schedule_json)
SELECT
    ('e0110000-0000-0000-0000-0000000000' || LPAD((ROW_NUMBER() OVER (ORDER BY c.id, t.pos))::TEXT, 2, '0'))::uuid,
    c.id,
    t.master_name,
    c.phone,
    t.specialization,
    TRUE,
    '{"work_days": [0,1,2,3,4,5,6], "start": "09:00", "end": "20:00"}'::jsonb
FROM service_centers c
CROSS JOIN (VALUES
    (1, 'Сергей Ковалёв', 'Автослесарь, ТО и ходовая часть'),
